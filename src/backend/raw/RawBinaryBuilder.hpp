#ifndef LSM_RAW_BINARY_BUILDER_HPP
#define LSM_RAW_BINARY_BUILDER_HPP

#include <vector>
#include <string>
#include <cstdint>
#include <fstream>
#include <stdexcept>
#include <cstring>

class RawBinaryBuilder {
public:
    static void buildRawBinary(const std::string& outputPath, const std::vector<uint8_t>& machineCode) {
        if (machineCode.empty()) {
            throw std::runtime_error("RawBinaryBuilder: Machine code payload is empty.");
        }
        std::ofstream outFile(outputPath, std::ios::binary);
        if (!outFile.is_open()) {
            throw std::runtime_error("RawBinaryBuilder: Failed to open output file: " + outputPath);
        }
        outFile.write(reinterpret_cast<const char*>(machineCode.data()), machineCode.size());
        outFile.close();
    }

    
    static void buildBootableImage(const std::string& outputPath, const std::vector<uint8_t>& kernelCode) {
        if (kernelCode.empty()) {
            throw std::runtime_error("RawBinaryBuilder: Kernel code is empty.");
        }

        std::vector<uint8_t> disk(1474560, 0); 
        std::vector<uint8_t> bootSector(512, 0);

        
        const uint8_t stage0[] = {
            0xFA, 0x31, 0xC0, 0x8E, 0xD8, 0x8E, 0xC0, 0x8E, 0xD0, 0xBC, 0x00, 0x7C,
            0xB4, 0x02, 0xB0, 0x10, 0xB9, 0x02, 0x00, 0x31, 0xD2, 0xB8, 0x00, 0x10,
            0x8E, 0xC0, 0x31, 0xDB, 0xCD, 0x13, 0xE4, 0x92, 0x0C, 0x02, 0xE6, 0x92,
            0x0F, 0x01, 0x16, 0x20, 0x7D, 0x0F, 0x20, 0xC0, 0x0C, 0x01, 0x0F, 0x22,
            0xC0, 0x66, 0xEA, 0x40, 0x7C, 0x00, 0x00, 0x08, 0x00
        };
        std::memcpy(&bootSector[0], stage0, sizeof(stage0));

        
        const uint8_t stage1[] = {
            0x66, 0xB8, 0x10, 0x00, 0x8E, 0xD8, 0x8E, 0xC0, 0x8E, 0xD0, 0xBF, 0x00,
            0x90, 0x00, 0x00, 0xB9, 0x00, 0x0C, 0x00, 0x00, 0x31, 0xC0, 0xF3, 0xAB,
            0xC7, 0x05, 0x00, 0x90, 0x00, 0x00, 0x03, 0xA0, 0x00, 0x00, 0xC7, 0x05,
            0x00, 0xA0, 0x00, 0x00, 0x03, 0xB0, 0x00, 0x00, 0xC7, 0x05, 0x00, 0xB0,
            0x00, 0x00, 0x83, 0x00, 0x00, 0x00, 0xB8, 0x00, 0x90, 0x00, 0x00, 0x0F,
            0x22, 0xD8, 0x0F, 0x20, 0xE0, 0x0D, 0x20, 0x00, 0x00, 0x00, 0x0F, 0x22,
            0xE0, 0xB9, 0x80, 0x00, 0x00, 0xC0, 0x0F, 0x32, 0x0D, 0x00, 0x01, 0x00,
            0x00, 0x0F, 0x30, 0x0F, 0x20, 0xC0, 0x0D, 0x00, 0x00, 0x00, 0x80, 0x0F,
            0x22, 0xC0, 0xEA, 0xE0, 0x7C, 0x00, 0x00, 0x18, 0x00
        };
        std::memcpy(&bootSector[0x40], stage1, sizeof(stage1));

        
        const uint8_t stage2[] = {
            0x66, 0xB8, 0x10, 0x00, 0x8E, 0xD8, 0x8E, 0xC0, 0x8E, 0xD0, 0x48, 0xBC,
            0x00, 0x00, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x48, 0x89, 0xE5, 0x48,
            0xB8, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0xFF, 0xE0
        };
        std::memcpy(&bootSector[0xE0], stage2, sizeof(stage2));

        
        const uint8_t gdtData[] = {
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0xFF, 0xFF, 0x00, 0x00, 0x00, 0x9A, 0xCF, 0x00,
            0xFF, 0xFF, 0x00, 0x00, 0x00, 0x92, 0xCF, 0x00,
            0x00, 0x00, 0x00, 0x00, 0x00, 0x9A, 0x20, 0x00
        };
        std::memcpy(&bootSector[0x100], gdtData, sizeof(gdtData));

        bootSector[0x120] = 0x1F; bootSector[0x121] = 0x00;
        bootSector[0x122] = 0x00; bootSector[0x123] = 0x7D; bootSector[0x124] = 0x00; bootSector[0x125] = 0x00;

        bootSector[510] = 0x55;
        bootSector[511] = 0xAA;

        std::memcpy(&disk[0], bootSector.data(), 512);
        std::memcpy(&disk[512], kernelCode.data(), kernelCode.size());

        buildRawBinary(outputPath, disk);
    }
};

#endif 